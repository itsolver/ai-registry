#!/usr/bin/env node

import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";

const SOURCE_URL =
  "https://artificialanalysis.ai/models/recommend?intelligence=6&cost=10&types=general%2Cinstruction-following&image=true&reasoning=true&providers=6047c38a-af71-4b47-9d66-d361753f71b4%2C80e7b7e3-e268-43db-a9b1-848693fbec85%2C50649676-6610-47a6-bb54-a2e213e6e414%2Ca7b7b981-8720-4260-92c4-ceb47e785efc&step=results";
const OUT_PATH = resolve("src/generated/aa-customer-support-recommendations.ts");
const TOP_SLUGS = [
  "grok-4-3",
  "gemini-3-1-pro-preview",
  "gpt-5-5-low",
  "gemini-3-flash-reasoning",
  "gpt-5-5-medium",
  "gpt-5-4-low",
  "gemini-3-5-flash",
  "gpt-5-4-nano",
  "gpt-5-4-nano-medium",
  "gpt-5-3-codex",
];

const response = await fetch(SOURCE_URL, {
  headers: {
    "user-agent": "IT Solver AI Registry weekly extractor",
  },
});

if (!response.ok) {
  throw new Error(`Artificial Analysis returned ${response.status}`);
}

const html = await response.text();
const models = extractModels(html);
const records = TOP_SLUGS.map((slug, index) => {
  const model = models.find((item) => item.url === `/models/${slug}`);
  if (!model) {
    throw new Error(`Missing Artificial Analysis recommendation model: ${slug}`);
  }
  return normalizeRecommendationRecord(model, index + 1);
});

const extractedAt = new Date().toISOString();
const content = `// Generated by scripts/extract-aa-customer-support-recommendations.mjs from ${SOURCE_URL}
export const AA_CUSTOMER_SUPPORT_RECOMMENDATIONS_EXTRACTED_AT = ${JSON.stringify(extractedAt)};
export const AA_CUSTOMER_SUPPORT_RECOMMENDATIONS_SOURCE_URL = ${JSON.stringify(SOURCE_URL)};
export const AA_CUSTOMER_SUPPORT_RECOMMENDATIONS = ${JSON.stringify(records, null, 2)} as const;
`;

mkdirSync(dirname(OUT_PATH), { recursive: true });
writeFileSync(OUT_PATH, content);
console.log(`Wrote ${records.length} customer support recommendation records to ${OUT_PATH}`);

function extractModels(html) {
  for (const payload of extractNextFlightStrings(html)) {
    if (!payload.includes('"models":[') || !payload.includes("intelligenceIndexCost")) {
      continue;
    }

    const keyIndex = payload.indexOf('"models":');
    const arrayStart = payload.indexOf("[", keyIndex);
    const arrayEnd = matchingBracket(payload, arrayStart);
    if (arrayStart === -1 || arrayEnd === -1) continue;

    const models = JSON.parse(payload.slice(arrayStart, arrayEnd + 1));
    if (Array.isArray(models) && models.some((model) => model?.intelligenceIndexCost)) {
      return models;
    }
  }

  throw new Error("No Artificial Analysis recommender model data found");
}

function extractNextFlightStrings(html) {
  const strings = [];
  const scriptPattern = /<script>self\.__next_f\.push\(([\s\S]*?)\)<\/script>/g;

  for (const match of html.matchAll(scriptPattern)) {
    try {
      const payload = JSON.parse(match[1]);
      for (const item of payload) {
        if (typeof item === "string") strings.push(item);
      }
    } catch {
      continue;
    }
  }

  return strings;
}

function matchingBracket(value, start) {
  if (start === -1) return -1;

  let depth = 0;
  let inString = false;
  let escaped = false;

  for (let index = start; index < value.length; index += 1) {
    const char = value[index];
    if (inString) {
      if (escaped) escaped = false;
      else if (char === "\\") escaped = true;
      else if (char === '"') inString = false;
      continue;
    }

    if (char === '"') inString = true;
    else if (char === "[") depth += 1;
    else if (char === "]") {
      depth -= 1;
      if (depth === 0) return index;
    }
  }

  return -1;
}

function normalizeRecommendationRecord(model, rank) {
  const slug = model.url?.split("/").filter(Boolean).at(-1);
  const provider = providerFromName(model.creator?.name);
  const inputPrice = numberOrUndefined(model.inputPrice);
  const outputPrice = numberOrUndefined(model.outputPrice);

  if (!slug || !provider || inputPrice === undefined || outputPrice === undefined) {
    throw new Error(`Incomplete recommendation record: ${model.name ?? slug ?? "unknown"}`);
  }

  return {
    rank,
    label: stringOrUndefined(model.name) ?? slug,
    slug,
    detailsUrl: `/models/${slug}`,
    provider,
    ...optionalNumber("intelligenceIndex", numberOrUndefined(model.intelligenceIndex)),
    ...optionalNumber("agenticScore", numberOrUndefined(model.agenticScore)),
    ...optionalNumber(
      "instructionFollowingScore",
      numberOrUndefined(model.instructionFollowingScore),
    ),
    ...optionalNumber("medianOutputSpeed", numberOrUndefined(model.medianOutputSpeed)),
    ...optionalNumber(
      "intelligenceIndexCost",
      numberOrUndefined(model.intelligenceIndexCost),
    ),
    inputPrice,
    outputPrice,
    ...optionalNumber("cacheHitPrice", numberOrUndefined(model.cachedInputPrice)),
    ...optionalNumber("contextWindow", numberOrUndefined(model.contextWindow)),
    imageInput: Boolean(model.imageInput),
    reasoning: Boolean(model.reasoning),
  };
}

function providerFromName(value) {
  const normalized = stringOrUndefined(value)?.toLowerCase();
  if (normalized === "openai") return "openai";
  if (normalized === "google") return "google";
  if (normalized === "xai") return "xai";
  if (normalized === "anthropic") return "anthropic";
  return undefined;
}

function stringOrUndefined(value) {
  return typeof value === "string" && value.trim() ? value.trim() : undefined;
}

function numberOrUndefined(value) {
  return typeof value === "number" && Number.isFinite(value) ? value : undefined;
}

function optionalNumber(key, value) {
  return value === undefined ? {} : { [key]: value };
}
