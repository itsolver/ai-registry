#!/usr/bin/env node

import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";

const SOURCE_URL = "https://artificialanalysis.ai/";
const OUT_PATH = resolve("src/generated/aa-llm-efficiency.ts");
const DATASETS = {
  intelligence: "Artificial Analysis Intelligence Index",
  cost: "Cost to Run Artificial Analysis Intelligence Index",
  tokens: "Output Tokens Used to Run Artificial Analysis Intelligence Index",
};

const response = await fetch(SOURCE_URL, {
  headers: {
    "user-agent": "IT Solver AI Registry weekly extractor",
  },
});

if (!response.ok) {
  throw new Error(`Artificial Analysis returned ${response.status}`);
}

const html = await response.text();
const datasets = extractJsonLdDatasets(html);
const records = mergeDatasets(datasets).sort((left, right) =>
  left.slug.localeCompare(right.slug),
);

if (!records.length) {
  throw new Error("No Artificial Analysis LLM efficiency records found");
}

const extractedAt = new Date().toISOString();
const content = `// Generated by scripts/extract-aa-llm-efficiency.mjs from ${SOURCE_URL}
export const AA_LLM_EFFICIENCY_EXTRACTED_AT = ${JSON.stringify(extractedAt)};
export const AA_LLM_EFFICIENCY_MODELS = ${JSON.stringify(records, null, 2)} as const;
`;

mkdirSync(dirname(OUT_PATH), { recursive: true });
writeFileSync(OUT_PATH, content);
console.log(`Wrote ${records.length} LLM efficiency records to ${OUT_PATH}`);

function extractJsonLdDatasets(html) {
  const datasets = new Map();
  const scriptPattern = /<script type="application\/ld\+json">([\s\S]*?)<\/script>/g;

  for (const match of html.matchAll(scriptPattern)) {
    const raw = decodeHtml(match[1]);
    let value;
    try {
      value = JSON.parse(raw);
    } catch {
      continue;
    }

    if (value?.["@type"] !== "Dataset" || !Array.isArray(value.data)) continue;
    datasets.set(value.name, value.data);
  }

  return datasets;
}

function mergeDatasets(datasets) {
  const bySlug = new Map();

  for (const item of datasets.get(DATASETS.intelligence) ?? []) {
    upsert(bySlug, item, {
      intelligenceIndex: numberOrUndefined(item.intelligenceIndex),
    });
  }

  for (const item of datasets.get(DATASETS.cost) ?? []) {
    upsert(bySlug, item, {
      intelligenceRunAnswerCost: numberOrUndefined(item.answerCost),
      intelligenceRunReasoningCost: numberOrUndefined(item.reasoningCost),
      intelligenceRunInputCost: numberOrUndefined(item.inputCost),
    });
  }

  for (const item of datasets.get(DATASETS.tokens) ?? []) {
    upsert(bySlug, item, {
      intelligenceRunAnswerTokens: numberOrUndefined(item.answerTokens),
      intelligenceRunReasoningTokens: numberOrUndefined(item.reasoningTokens),
    });
  }

  return [...bySlug.values()]
    .map((record) => ({
      ...record,
      ...optionalNumber(
        "intelligenceRunTotalCost",
        sumDefined([
          record.intelligenceRunAnswerCost,
          record.intelligenceRunReasoningCost,
          record.intelligenceRunInputCost,
        ]),
      ),
      ...optionalNumber(
        "intelligenceRunOutputTokens",
        sumDefined([
          record.intelligenceRunAnswerTokens,
          record.intelligenceRunReasoningTokens,
        ]),
      ),
    }))
    .filter(
      (record) =>
        record.intelligenceIndex !== undefined ||
        record.intelligenceRunTotalCost !== undefined ||
        record.intelligenceRunOutputTokens !== undefined,
    );
}

function upsert(bySlug, item, values) {
  const detailsUrl = stringOrUndefined(item.detailsUrl);
  const slug = detailsUrl?.split("/").filter(Boolean).at(-1);
  if (!detailsUrl || !slug) return;

  const existing = bySlug.get(slug) ?? {
    label: stringOrUndefined(item.label) ?? slug,
    slug,
    detailsUrl,
  };

  bySlug.set(slug, {
    ...existing,
    ...Object.fromEntries(
      Object.entries(values).filter(([, value]) => value !== undefined),
    ),
  });
}

function decodeHtml(value) {
  return value
    .replaceAll("&quot;", '"')
    .replaceAll("&amp;", "&")
    .replaceAll("&#x27;", "'")
    .replaceAll("&lt;", "<")
    .replaceAll("&gt;", ">");
}

function stringOrUndefined(value) {
  return typeof value === "string" && value.trim() ? value.trim() : undefined;
}

function numberOrUndefined(value) {
  return typeof value === "number" && Number.isFinite(value) ? value : undefined;
}

function optionalNumber(key, value) {
  return value === undefined ? {} : { [key]: value };
}

function sumDefined(values) {
  const numbers = values.filter((value) => value !== undefined);
  if (!numbers.length) return undefined;
  return numbers.reduce((sum, value) => sum + value, 0);
}
