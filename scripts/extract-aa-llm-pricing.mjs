#!/usr/bin/env node

import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";

const SOURCE_URL = "https://artificialanalysis.ai/models";
const OUT_PATH = resolve("src/generated/aa-llm-pricing.ts");
const DATASET_NAME = "Pricing: Cache Hit, Input, and Output";

const response = await fetch(SOURCE_URL, {
  headers: {
    "user-agent": "IT Solver AI Registry weekly extractor",
  },
});

if (!response.ok) {
  throw new Error(`Artificial Analysis returned ${response.status}`);
}

const html = await response.text();
const records = extractPricingRecords(html).sort((left, right) =>
  left.slug.localeCompare(right.slug),
);

if (!records.length) {
  throw new Error("No Artificial Analysis LLM pricing records found");
}

const extractedAt = new Date().toISOString();
const content = `// Generated by scripts/extract-aa-llm-pricing.mjs from ${SOURCE_URL}
export const AA_LLM_PRICING_EXTRACTED_AT = ${JSON.stringify(extractedAt)};
export const AA_LLM_PRICING_MODELS = ${JSON.stringify(records, null, 2)} as const;
`;

mkdirSync(dirname(OUT_PATH), { recursive: true });
writeFileSync(OUT_PATH, content);
console.log(`Wrote ${records.length} LLM pricing records to ${OUT_PATH}`);

function extractPricingRecords(html) {
  const datasets = extractJsonLdDatasets(html);
  const pricingRows = datasets.get(DATASET_NAME) ?? [];

  return pricingRows
    .map((item) => normalizePricingRecord(item))
    .filter((record) => record !== undefined);
}

function extractJsonLdDatasets(html) {
  const datasets = new Map();
  const scriptPattern = /<script type="application\/ld\+json">([\s\S]*?)<\/script>/g;

  for (const match of html.matchAll(scriptPattern)) {
    const raw = decodeHtml(match[1]);
    let value;
    try {
      value = JSON.parse(raw);
    } catch {
      continue;
    }

    if (value?.["@type"] !== "Dataset" || !Array.isArray(value.data)) continue;
    datasets.set(value.name, value.data);
  }

  return datasets;
}

function normalizePricingRecord(item) {
  const detailsUrl = stringOrUndefined(item.detailsUrl);
  const slug = detailsUrl?.split("/").filter(Boolean).at(-1);
  const label = stringOrUndefined(item.label) ?? slug;
  if (!detailsUrl || !slug || !label || !Array.isArray(item.pricing)) return undefined;

  const prices = Object.fromEntries(
    item.pricing
      .map((price) => [price.name, numberOrUndefined(price.value)])
      .filter(([, value]) => value !== undefined),
  );

  const inputPrice = prices.inputPrice;
  const outputPrice = prices.outputPrice;
  if (inputPrice === undefined || outputPrice === undefined) return undefined;

  return {
    label,
    slug,
    detailsUrl,
    ...optionalNumber("cacheHitPrice", prices.cacheHitPrice),
    inputPrice,
    outputPrice,
  };
}

function decodeHtml(value) {
  return value
    .replaceAll("&quot;", '"')
    .replaceAll("&amp;", "&")
    .replaceAll("&#x27;", "'")
    .replaceAll("&lt;", "<")
    .replaceAll("&gt;", ">");
}

function stringOrUndefined(value) {
  return typeof value === "string" && value.trim() ? value.trim() : undefined;
}

function numberOrUndefined(value) {
  return typeof value === "number" && Number.isFinite(value) ? value : undefined;
}

function optionalNumber(key, value) {
  return value === undefined ? {} : { [key]: value };
}
