#!/usr/bin/env node

import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";

const SOURCE_URL = "https://artificialanalysis.ai/speech-to-speech";
const OUT_PATH = resolve("src/generated/aa-speech-to-speech.ts");
const SUPPORTED_PROVIDERS = new Set(["openai", "google", "xai", "anthropic"]);

const response = await fetch(SOURCE_URL, {
  headers: {
    "user-agent": "IT Solver AI Registry weekly extractor",
  },
});

if (!response.ok) {
  throw new Error(`Artificial Analysis returned ${response.status}`);
}

const html = await response.text();
const records = extractRecords(html)
  .filter((record) => SUPPORTED_PROVIDERS.has(record.provider))
  .sort((left, right) => left.provider.localeCompare(right.provider) || left.slug.localeCompare(right.slug));

if (!records.length) {
  throw new Error("No Artificial Analysis speech-to-speech records found");
}

const extractedAt = new Date().toISOString();
const content = `// Generated by scripts/extract-aa-speech-to-speech.mjs from ${SOURCE_URL}
export const AA_SPEECH_TO_SPEECH_EXTRACTED_AT = ${JSON.stringify(extractedAt)};
export const AA_SPEECH_TO_SPEECH_MODELS = ${JSON.stringify(records, null, 2)} as const;
`;

mkdirSync(dirname(OUT_PATH), { recursive: true });
writeFileSync(OUT_PATH, content);
console.log(`Wrote ${records.length} speech-to-speech records to ${OUT_PATH}`);

function extractRecords(html) {
  const decoded = html.replaceAll('\\"', '"');
  const objectPattern = /\{"id":"[\s\S]*?"defaultSelected":(?:true|false)\}/g;
  const bySlug = new Map();

  for (const match of decoded.matchAll(objectPattern)) {
    const record = parseRecord(match[0]);
    if (!record) continue;

    const existing = bySlug.get(record.slug);
    if (!existing || completeness(record) > completeness(existing)) {
      bySlug.set(record.slug, record);
    }
  }

  return [...bySlug.values()];
}

function parseRecord(raw) {
  let value;
  try {
    value = JSON.parse(raw);
  } catch {
    return undefined;
  }

  const provider = stringOrUndefined(value.host?.slug);
  const slug = stringOrUndefined(value.slug);
  if (!provider || !slug) return undefined;

  const record = {
    id: stringOrUndefined(value.id) || slug,
    name: stringOrUndefined(value.name) || slug,
    shortName: stringOrUndefined(value.shortName) || stringOrUndefined(value.name) || slug,
    slug,
    provider,
    providerName: stringOrUndefined(value.host?.name) || provider,
    modelSlug: stringOrUndefined(value.model?.slug) || slug,
    bbaScore: numberOrUndefined(value.bbaScore),
    tauVoiceAggScore: numberOrUndefined(value.tauVoiceAggScore),
    tauVoiceTelecomScore: numberOrUndefined(value.tauVoiceScoresByCategory?.telecom?.avg_reward),
    tauVoiceRetailScore: numberOrUndefined(value.tauVoiceScoresByCategory?.retail?.avg_reward),
    tauVoiceAirlineScore: numberOrUndefined(value.tauVoiceScoresByCategory?.airline?.avg_reward),
    fdbScore: numberOrUndefined(value.fdbScore),
    timeToFirstAudioSeconds: numberOrUndefined(value.timeToFirstAudioSeconds),
    costPerHourOfInputAudio: numberOrUndefined(value.costPerHourOfInputAudio),
    pricePerHourInput: numberOrUndefined(value.pricePerHourInput),
    pricePerHourOutput: numberOrUndefined(value.pricePerHourOutput),
    averageCostPerTask: numberOrUndefined(value.averageCostPerTask),
  };

  if (
    record.bbaScore === undefined &&
    record.tauVoiceAggScore === undefined &&
    record.timeToFirstAudioSeconds === undefined &&
    record.costPerHourOfInputAudio === undefined
  ) {
    return undefined;
  }

  return record;
}

function completeness(record) {
  return Object.values(record).filter((value) => value !== undefined).length;
}

function stringOrUndefined(value) {
  return typeof value === "string" && value.trim() ? value.trim() : undefined;
}

function numberOrUndefined(value) {
  return typeof value === "number" && Number.isFinite(value) ? value : undefined;
}
