#!/usr/bin/env node

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const SOURCE_URL = "https://artificialanalysis.ai/speech-to-text/batch";
const OUT_PATH = resolve("src/generated/aa-speech-to-text.ts");
const SUPPORTED_PROVIDERS = new Map([
  ["anthropic", "Anthropic"],
  ["elevenlabs", "ElevenLabs"],
  ["google", "Google"],
  ["groq", "Groq"],
  ["nvidia", "NVIDIA"],
  ["openai", "OpenAI"],
  ["xai", "xAI"],
]);

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await main();
}

async function main() {
  const html = process.argv[2]
    ? readFileSync(resolve(process.argv[2]), "utf8")
    : await fetchSourceHtml();
  const records = extractSpeechToTextRecords(html).sort(
    (left, right) =>
      left.providers[0].price_per_1k_minutes -
        right.providers[0].price_per_1k_minutes ||
      left.id.localeCompare(right.id),
  );

  if (!records.length) {
    throw new Error("No Artificial Analysis speech-to-text records found");
  }

  const extractedAt = new Date().toISOString();
  const recordsWithTimestamp = records.map((record) => ({
    ...record,
    extractedAt,
  }));
  const content = `// Generated by scripts/extract-aa-speech-to-text.mjs from ${SOURCE_URL}
export const AA_SPEECH_TO_TEXT_EXTRACTED_AT = ${JSON.stringify(extractedAt)};
export const AA_SPEECH_TO_TEXT_SOURCE_URL = ${JSON.stringify(SOURCE_URL)};
export const AA_SPEECH_TO_TEXT_MODELS = ${JSON.stringify(recordsWithTimestamp, null, 2)} as const;
`;

  mkdirSync(dirname(OUT_PATH), { recursive: true });
  writeFileSync(OUT_PATH, content);
  console.log(`Wrote ${records.length} speech-to-text records to ${OUT_PATH}`);
}

async function fetchSourceHtml() {
  const response = await fetch(SOURCE_URL, {
    headers: {
      "user-agent": "IT Solver AI Registry weekly extractor",
    },
  });

  if (!response.ok) {
    throw new Error(`Artificial Analysis returned ${response.status}`);
  }

  return response.text();
}

export function extractSpeechToTextRecords(html) {
  const byId = new Map();

  for (const cells of extractTableRows(html)) {
    if (cells.length < 6) continue;

    const name = cells[0];
    const creatorProvider = providerFromName(name);
    const hostProvider = providerFromName(cells[1]);
    const provider = creatorProvider ?? hostProvider;
    const aaWer = numberOrUndefined(cells[3]);
    const speedFactor = numberOrUndefined(cells[4]);
    const pricePer1kMinutes = numberOrUndefined(cells[5]);
    if (
      !name ||
      !provider ||
      aaWer === undefined ||
      speedFactor === undefined ||
      pricePer1kMinutes === undefined
    ) {
      continue;
    }

    const providerName = SUPPORTED_PROVIDERS.get(provider);
    const hostName = cells[1] || providerName;
    const hostSlug = hostProvider ? hostProvider : hostSlugFromName(hostName);
    const slug = slugFrom(modelSlugName(name, providerName));
    const id = [
      provider,
      slug,
      hostSlug && hostSlug !== provider ? hostSlug : "",
    ]
      .filter(Boolean)
      .join("-");
    byId.set(id, {
      id,
      name,
      slug,
      model_creator: {
        name: providerName,
        slug: provider,
      },
      aa_wer_index: aaWer,
      providers: [
        {
          name: hostName,
          slug: hostSlug,
          price_per_1k_minutes: pricePer1kMinutes,
          median_speed_factor: speedFactor,
          aa_wer_index: aaWer,
        },
      ],
    });
  }

  return [...byId.values()];
}

function extractTableRows(html) {
  return [...html.matchAll(/<tr\b[\s\S]*?<\/tr>/gi)]
    .map((rowMatch) =>
      [...rowMatch[0].matchAll(/<td\b[\s\S]*?<\/td>/gi)].map((cellMatch) =>
        textFromHtml(cellMatch[0]),
      ),
    )
    .filter((cells) => cells.length);
}

function textFromHtml(value) {
  return decodeHtml(value.replace(/<[^>]+>/g, " "))
    .replace(/\s+/g, " ")
    .trim();
}

function decodeHtml(value) {
  return value
    .replace(/&nbsp;/g, " ")
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'");
}

function providerFromName(value) {
  const normalized = value.toLowerCase().replace(/[^a-z0-9]+/g, "");
  if (normalized.includes("elevenlabs")) return "elevenlabs";
  if (normalized.includes("anthropic")) return "anthropic";
  if (normalized.includes("google")) return "google";
  if (normalized.includes("groq")) return "groq";
  if (normalized.includes("nvidia")) return "nvidia";
  if (normalized.includes("openai")) return "openai";
  if (normalized.includes("xai")) return "xai";
  return undefined;
}

function numberOrUndefined(value) {
  const match = value.replace(/,/g, "").match(/-?\d+(?:\.\d+)?/);
  if (!match) return undefined;
  const number = Number(match[0]);
  return Number.isFinite(number) ? number : undefined;
}

function modelSlugName(name, providerName) {
  if (!providerName) return name;
  return name.replace(
    new RegExp(`,\\s*${escapeRegExp(providerName)}$`, "i"),
    "",
  );
}

function hostSlugFromName(name) {
  const normalized = name.toLowerCase().replace(/[^a-z0-9]+/g, "");
  if (normalized === "togetherai") return "togetherai";
  return slugFrom(name);
}

function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function slugFrom(value) {
  return value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}
